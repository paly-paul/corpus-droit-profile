function renderIcons() {
  document.querySelectorAll('i[data-lucide]').forEach(function(el) {
    var name = el.getAttribute('data-lucide');
    var inner = window.ICONS[name];
    if (!inner) return;
    // Inherit size from class attribute (w-N h-N pattern) or default to 16
    var w = 16, h = 16;
    var cls = el.className || '';
    var wm = cls.match(/w-([\d.]+)/);
    var hm = cls.match(/h-([\d.]+)/);
    if (wm) w = Math.round(parseFloat(wm[1]) * 4);
    if (hm) h = Math.round(parseFloat(hm[1]) * 4);
    var svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', w);
    svg.setAttribute('height', h);
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.style.display = 'inline-block';
    svg.style.verticalAlign = 'middle';
    svg.style.flexShrink = '0';
    if (el.className) svg.setAttribute('class', el.className);
    svg.innerHTML = inner;
    el.parentNode.replaceChild(svg, el);
  });
}

